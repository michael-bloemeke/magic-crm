#!/usr/bin/env node
// Writes mobile/email-templates.js from src/emailTemplates.ts, so the phone's composer offers exactly
// the Mac's template library. The Mac file stays the source of truth: re-run this whenever a template
// changes (Node 22: node --experimental-strip-types scripts/gen-phone-email-templates.mjs), then
// `npm run sync`.
//
// The only change made on the way through: a GIF's src points at the public `email-gifs` storage
// bucket instead of the Mac's local /api/email-gif route, so it animates in the phone's composer.
// The data-crm-gif attribute is kept, and that is what the send-email function embeds (cid:), so the
// client receives the GIF itself, exactly as from the Mac. If a GIF is added to email-gifs/, upload it
// to the bucket too.
import { writeFileSync } from 'node:fs'
import { TEMPLATE_GROUPS } from '../src/emailTemplates.ts'
const GIF_BASE = 'https://yfmacqvcmkogvkcxfjkr.supabase.co/storage/v1/object/public/email-gifs/'
const groups = TEMPLATE_GROUPS.map((g) => ({
  id: g.id,
  name: g.name,
  templates: g.templates.map((t) => ({
    id: t.id,
    name: t.name,
    subject: t.subject,
    body: t.body.replace(/src="\/api\/email-gif\/([a-z0-9-]+)"/g, (_, slug) => `src="${GIF_BASE}${slug}.gif"`),
    ...(t.needsRewrite ? { needsRewrite: true } : {}),
  })),
}))
const out = `// GENERATED by scripts/gen-phone-email-templates.mjs from src/emailTemplates.ts on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand: change src/emailTemplates.ts and re-run the script.
export const TEMPLATE_GROUPS = ${JSON.stringify(groups, null, 2)}
export function findTemplate(id) {
  for (const g of TEMPLATE_GROUPS) for (const t of g.templates) if (t.id === id) return t
  return null
}
`
writeFileSync(new URL('../mobile/email-templates.js', import.meta.url), out)
console.log('wrote mobile/email-templates.js:', groups.reduce((n, g) => n + g.templates.length, 0), 'templates')
