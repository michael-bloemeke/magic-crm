// The signed-agreement PDF, rendered in the CLOUD.
//
// WHY THIS EXISTS. The Mac renders contracts with pdfmake, which needs real font files and reads
// Georgia out of /System/Library/Fonts. That cannot run in a Deno edge function, and it was the one
// thing keeping the end of the booking chain tied to Michael's laptop being open.
//
// pdf-lib is pure JavaScript and runs anywhere, and the PDF format's base-14 fonts (Times, here) are
// guaranteed present in every viewer without embedding anything. So this renderer needs no font
// files, no licensing question, and no filesystem.
//
// Coordinates: pdf-lib's origin is the BOTTOM-left and y grows upward, the opposite of screen
// drawing. Everything here is written bottom-up on purpose.

import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "npm:pdf-lib@1.17.1";

const PAGE_W = 612;
const PAGE_H = 792;
const MARGIN = 66;
const CONTENT_W = PAGE_W - MARGIN * 2;
const FOOT = MARGIN + 20;

const INK = rgb(0.12, 0.11, 0.09);
const MUTED = rgb(0.42, 0.39, 0.35);
const RULE = rgb(0.72, 0.68, 0.62);

const BRAND = "THE AWARD-WINNING MAGIC OF MICHAEL BLOEMEKE";
const TITLE = "PERFORMANCE SERVICES AGREEMENT";
// Countersignature. Kept beside the brand string so the two never drift apart.
const PERFORMER_NAME = "Michael Bloemeke";

export interface Fonts {
  reg: PDFFont;
  bold: PDFFont;
  italic: PDFFont;
}

export interface Signature {
  name: string;
  date: string;
  signedAt: string;
  ip?: string;
}

type Block =
  | { kind: "heading"; text: string }
  | { kind: "para"; text: string }
  | { kind: "bullets"; items: string[] };

// ---------------------------------------------------------------------------
// Turning the stored agreement HTML into blocks
// ---------------------------------------------------------------------------
//
// The markup is machine-generated by the CRM's own contract template and is deliberately narrow:
// <p>, <p data-section> for numbered clause headings, and <ul><li>. Parsing it here (rather than
// storing a second structured copy) means the PDF can never disagree with what the client read on
// the website, because both come from the same string.

function decodeEntities(s: string): string {
  return s
    .replace(/&nbsp;/gi, " ")
    .replace(/&amp;/gi, "&")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;/gi, "'")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">");
}

const stripTags = (s: string) => decodeEntities(s.replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();

export function parseAgreement(html: string): Block[] {
  const blocks: Block[] = [];
  // One pass over the top-level elements, in document order.
  const re = /<ul[^>]*>([\s\S]*?)<\/ul>|<p([^>]*)>([\s\S]*?)<\/p>/gi;
  let m: RegExpExecArray | null;
  while ((m = re.exec(html))) {
    if (m[1] !== undefined) {
      const items = [...m[1].matchAll(/<li[^>]*>([\s\S]*?)<\/li>/gi)]
        .map((li) => stripTags(li[1]))
        .filter(Boolean);
      if (items.length) blocks.push({ kind: "bullets", items });
      continue;
    }
    const attrs = m[2] || "";
    const text = stripTags(m[3] || "");
    if (!text) continue;
    blocks.push({ kind: /data-section/i.test(attrs) ? "heading" : "para", text });
  }
  return blocks;
}

// ---------------------------------------------------------------------------
// Layout helpers
// ---------------------------------------------------------------------------

function wrap(text: string, font: PDFFont, size: number, maxW: number): string[] {
  const out: string[] = [];
  for (const para of String(text).split("\n")) {
    let line = "";
    for (const word of para.split(/\s+/)) {
      const next = line ? `${line} ${word}` : word;
      // widthOfTextAtSize throws on characters the base-14 font cannot encode; fall back to a
      // rough estimate rather than failing the whole document over one odd glyph.
      let w: number;
      try {
        w = font.widthOfTextAtSize(next, size);
      } catch {
        w = next.length * size * 0.5;
      }
      if (w > maxW && line) {
        out.push(line);
        line = word;
      } else {
        line = next;
      }
    }
    out.push(line);
  }
  return out;
}

// The base-14 fonts are single-byte WinAnsi. A curly quote or dash from a client's own typing would
// otherwise throw during draw, so fold the common ones down to ASCII first.
function sanitize(s: string): string {
  return String(s ?? "")
    .replace(/[‘’‚‛]/g, "'")
    .replace(/[“”„]/g, '"')
    .replace(/[–—]/g, "-")
    .replace(/…/g, "...")
    .replace(/ /g, " ")
    // Anything still outside Latin-1 is dropped rather than allowed to break the render.
    .replace(/[^\x09\x0A\x0D\x20-\xFF]/g, "");
}

class Writer {
  doc: PDFDocument;
  fonts: Fonts;
  page!: PDFPage;
  y = 0;

  constructor(doc: PDFDocument, fonts: Fonts) {
    this.doc = doc;
    this.fonts = fonts;
    this.newPage();
  }
  newPage() {
    this.page = this.doc.addPage([PAGE_W, PAGE_H]);
    this.y = PAGE_H - MARGIN;
  }
  ensure(h: number) {
    if (this.y - h < FOOT) this.newPage();
  }
  text(s: string, opts: { size?: number; font?: keyof Fonts; color?: typeof INK; x?: number; gap?: number } = {}) {
    const size = opts.size ?? 10.5;
    const font = this.fonts[opts.font ?? "reg"];
    const x = opts.x ?? MARGIN;
    const lines = wrap(sanitize(s), font, size, PAGE_W - MARGIN - x);
    for (const line of lines) {
      this.ensure(size + 3);
      this.page.drawText(line, { x, y: this.y, size, font, color: opts.color ?? INK });
      this.y -= size * 1.32;
    }
    this.y -= opts.gap ?? 0;
  }
  rule(gap = 10) {
    this.ensure(gap + 6);
    this.page.drawLine({
      start: { x: MARGIN, y: this.y },
      end: { x: PAGE_W - MARGIN, y: this.y },
      thickness: 0.75,
      color: RULE,
    });
    this.y -= gap;
  }
}

// ---------------------------------------------------------------------------
// The document
// ---------------------------------------------------------------------------

export async function buildAgreementPdf(opts: {
  clientName: string;
  agreementHtml: string;
  summary: { label: string; value: string }[];
  signature: Signature | null;
}): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const fonts: Fonts = {
    reg: await doc.embedFont(StandardFonts.TimesRoman),
    bold: await doc.embedFont(StandardFonts.TimesRomanBold),
    italic: await doc.embedFont(StandardFonts.TimesRomanItalic),
  };
  const w = new Writer(doc, fonts);

  // --- Page 1: what they told us -------------------------------------------
  w.text("YOUR EVENT DETAILS", { size: 15, font: "bold" });
  w.y -= 5;
  w.text(`Prepared for ${opts.clientName}`, { size: 10.5, color: MUTED });
  w.y -= 4;
  w.rule(16);
  w.text(
    "These are the details you gave me. They form part of the agreement on the following pages, so if anything here is wrong, tell me before the event.",
    { size: 10, gap: 12 },
  );

  if (opts.summary.length) {
    for (const row of opts.summary) {
      const valueLines = wrap(sanitize(row.value), fonts.reg, 10.5, CONTENT_W);
      w.ensure(16 + valueLines.length * 14 + 8);
      w.text(row.label.toUpperCase(), { size: 8.5, font: "bold", color: MUTED });
      w.y += 2;
      w.text(row.value, { size: 10.5, gap: 6 });
    }
  } else {
    w.text("No booking form has been submitted for this project yet.", { size: 10, font: "italic", color: MUTED });
  }

  // --- Page 2+: the agreement ----------------------------------------------
  w.newPage();
  w.text(BRAND, { size: 11.5, font: "bold" });
  w.y -= 2;
  w.text(TITLE, { size: 15, font: "bold" });
  w.y -= 2;
  w.rule(14);

  for (const b of parseAgreement(opts.agreementHtml)) {
    if (b.kind === "heading") {
      w.ensure(30);
      w.y -= 6;
      w.text(b.text, { size: 11.5, font: "bold", gap: 3 });
    } else if (b.kind === "para") {
      w.text(b.text, { size: 10.5, gap: 6 });
    } else {
      for (const item of b.items) {
        const lines = wrap(sanitize(item), fonts.reg, 10.5, CONTENT_W - 16);
        w.ensure(lines.length * 14 + 4);
        w.page.drawText("-", { x: MARGIN + 3, y: w.y, size: 10.5, font: fonts.reg, color: INK });
        w.text(item, { size: 10.5, x: MARGIN + 16, gap: 2 });
      }
      w.y -= 4;
    }
  }

  // --- The signature -------------------------------------------------------
  // Needs about 150pt of clear air. Start a fresh page rather than crowd it, which is also what
  // makes the block's position predictable instead of depending on how long the contract ran.
  w.ensure(150);
  w.y -= 14;
  w.rule(20);

  const sig = opts.signature;
  const halfW = (CONTENT_W - 20) / 2;

  // Ticked box, drawn rather than a form field: a field can be retyped by whoever opens the file,
  // and a receipt you can edit is not a receipt.
  w.ensure(120);
  const boxY = w.y - 11;
  w.page.drawRectangle({
    x: MARGIN, y: boxY, width: 13, height: 13,
    borderWidth: 1, borderColor: RULE, color: rgb(0.98, 0.97, 0.94),
  });
  if (sig) {
    w.page.drawLine({ start: { x: MARGIN + 2.5, y: boxY + 6 }, end: { x: MARGIN + 5.5, y: boxY + 2.5 }, thickness: 1.4, color: INK });
    w.page.drawLine({ start: { x: MARGIN + 5.5, y: boxY + 2.5 }, end: { x: MARGIN + 10.5, y: boxY + 10.5 }, thickness: 1.4, color: INK });
  }
  w.page.drawText("I have read this Agreement and I approve it.", {
    x: MARGIN + 20, y: boxY + 2.5, size: 10, font: fonts.bold, color: INK,
  });
  w.y = boxY - 34;

  const name = sanitize(sig?.name || "");
  const date = sanitize(sig?.date || "");
  if (name) w.page.drawText(name, { x: MARGIN, y: w.y, size: 15, font: fonts.italic, color: INK });
  if (date) w.page.drawText(date, { x: MARGIN + halfW + 20, y: w.y, size: 11, font: fonts.reg, color: INK });
  w.y -= 6;
  w.page.drawLine({ start: { x: MARGIN, y: w.y }, end: { x: MARGIN + halfW, y: w.y }, thickness: 0.75, color: RULE });
  w.page.drawLine({ start: { x: MARGIN + halfW + 20, y: w.y }, end: { x: PAGE_W - MARGIN, y: w.y }, thickness: 0.75, color: RULE });
  w.y -= 12;
  w.page.drawText("Client signature (typed name)", { x: MARGIN, y: w.y, size: 8, font: fonts.reg, color: MUTED });
  w.page.drawText("Date", { x: MARGIN + halfW + 20, y: w.y, size: 8, font: fonts.reg, color: MUTED });
  w.y -= 16;

  // THE COUNTERSIGNATURE. Clause 10 says "By signing below, both the Client and the Performer
  // acknowledge...", and SIGNATURE_LINES has always defined two lines, but only the client's was
  // ever drawn. The document promised a signature it never showed. Added 2026-08-04.
  //
  // Typed, exactly like the client's, because that is what the audit line below already says both
  // parties accepted. An image of a signature would look weightier and prove less: it can be copied
  // out of any PDF, whereas this sits beside a timestamped server-side record of the client's own
  // submission.
  //
  // Only drawn once the client has actually signed. On an unsigned preview a countersignature would
  // be claiming Michael had accepted an agreement nobody has agreed to yet.
  if (sig) {
    w.y -= 10;
    w.page.drawText(sanitize(PERFORMER_NAME), { x: MARGIN, y: w.y, size: 15, font: fonts.italic, color: INK });
    const counterDate = sanitize(sig.date || "");
    if (counterDate) w.page.drawText(counterDate, { x: MARGIN + halfW + 20, y: w.y, size: 11, font: fonts.reg, color: INK });
    w.y -= 6;
    w.page.drawLine({ start: { x: MARGIN, y: w.y }, end: { x: MARGIN + halfW, y: w.y }, thickness: 0.75, color: RULE });
    w.page.drawLine({ start: { x: MARGIN + halfW + 20, y: w.y }, end: { x: PAGE_W - MARGIN, y: w.y }, thickness: 0.75, color: RULE });
    w.y -= 12;
    w.page.drawText("Performer signature (typed name)", { x: MARGIN, y: w.y, size: 8, font: fonts.reg, color: MUTED });
    w.page.drawText("Date", { x: MARGIN + halfW + 20, y: w.y, size: 8, font: fonts.reg, color: MUTED });
    w.y -= 16;
  }

  if (sig) {
    // The audit trail. This is what makes a typed name defensible: not a picture of a signature, but
    // a contemporaneous record of who submitted what, when, and from where.
    const when = stampET(sig.signedAt);
    for (const line of [
      `Signed electronically on michaelbloemeke.com${when ? ` on ${when}` : ""}.`,
      sig.ip ? `Confirmed from IP address ${sig.ip}.` : "",
      "Typing a name in place of a signature was accepted by both parties as binding.",
    ].filter(Boolean)) {
      w.page.drawText(sanitize(line), { x: MARGIN, y: w.y, size: 8, font: fonts.italic, color: MUTED });
      w.y -= 10;
    }
  }

  return await doc.save();
}

// Written-out timestamp in Michael's timezone. House rule is 12-hour times and dates spelled out,
// and this is a line a client (or one day a lawyer) reads.
function stampET(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "";
  return d.toLocaleString("en-US", {
    timeZone: "America/New_York",
    month: "long", day: "numeric", year: "numeric",
    hour: "numeric", minute: "2-digit",
  }) + " ET";
}
