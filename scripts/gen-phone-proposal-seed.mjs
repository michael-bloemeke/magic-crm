#!/usr/bin/env node
// Writes supabase/functions/phone-api/proposal-seed.ts from the constants in crm-proposals.mjs, so the
// phone's "Start a proposal" seeds exactly what the Mac's does. The Mac file stays the source of
// truth: re-run this (Node 22) whenever REVIEW_BANK, PHOTO_SETS, CLIENT_LOGOS or DEFAULT_VIDEO_ID
// change, then redeploy phone-api.
import { writeFileSync } from 'node:fs'
import { REVIEW_BANK, PHOTO_SETS, CLIENT_LOGOS, DEFAULT_VIDEO_ID } from '../crm-proposals.mjs'
const out = `// GENERATED by scripts/gen-phone-proposal-seed.mjs from crm-proposals.mjs on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand: change crm-proposals.mjs and re-run the script.
export const REVIEW_BANK: Record<string, Array<{ name: string; text: string }>> = ${JSON.stringify(REVIEW_BANK, null, 2)}
export const PHOTO_SETS: Record<string, Record<string, unknown>> = ${JSON.stringify(PHOTO_SETS, null, 2)}
export const CLIENT_LOGOS: Array<{ logo: string; name: string }> = ${JSON.stringify(CLIENT_LOGOS, null, 2)}
export const DEFAULT_VIDEO_ID = ${JSON.stringify(DEFAULT_VIDEO_ID)}
`
writeFileSync(new URL('../supabase/functions/phone-api/proposal-seed.ts', import.meta.url), out)
console.log('wrote proposal-seed.ts')
process.exit(0)
